"""PersonaPlex shared-Mimi-decoder benchmark: {per-request, shared} x {eager, CUDA graphs}.

Sweeps the four Stage-1 decoder configurations of the shared-decoder PR (RFC
#7389 W4) across duplex session counts. Each (cell, sessions) combination
launches a fresh server with a thin overlay on
``vllm_omni/deploy/personaplex.yaml`` and drives it with the paced
multi-session load mode of
``tests/e2e/online_serving/personaplex_realtime_duplex.py`` (80 ms input
frames, one paced websocket session per duplex slot).

Cells (Stage-1 ``hf_overrides``):

  ===== ============================= ========================= ====================
  cell  decoder                       mimi_shared_decoder        mimi_cuda_graphs
  ===== ============================= ========================= ====================
  A     one B=1 codec per session      false                     false
  B     one B=1 codec per session      false                     true
  C     one width-N codec, row leases  true                      false
  D     one width-N codec, row leases  true                      true
  ===== ============================= ========================= ====================

``mimi_cuda_graphs`` is set on both stages so a cell is uniformly graphs-on
or graphs-off (Stage 0 encode graphs included).

Per (cell, sessions) the wrapper reports the session pass rate, median
client_stream_rtf, time-to-first-packet, underrun events, packet-interval
p99, server load time, the server process group's GPU memory after weight
load (where the (N-1) saved codec weight copies of cells C/D show up), and
the last Mimi decode-graph hit rate logged by the server. One warmup run
then ``--runs`` recorded runs per cell, matching the PR evidence methodology
("1 warmup + 3 recorded runs per cell"). Session-level acceptance failures
do not fail the sweep — cell A falling over at high N is part of the
evidence — but infrastructure failures (server crash, driver crash) do.

Requirements: the serving venv on PATH (or run from the repo root with
``vllm_omni`` importable), ``websockets`` and ``httpx`` installed, and
``nvidia-smi`` for the memory probe.
"""

import argparse
import hashlib
import json
import os
import signal
import statistics
import subprocess
import sys
import time
from pathlib import Path

import httpx

REPO = Path(__file__).resolve().parents[2]
DRIVER = REPO / "tests/e2e/online_serving/personaplex_realtime_duplex.py"
DEFAULT_MODEL = "nvidia/personaplex-7b-v1"

# cell -> (mimi_shared_decoder, mimi_cuda_graphs)
CELLS = {
    "A": (False, False),
    "B": (False, True),
    "C": (True, False),
    "D": (True, True),
}


def _stats(values: list[float]) -> dict[str, float]:
    """Mean/median/stdev/p95/min/max/n for a list of per-session measurements."""
    n = len(values)
    if n == 0:
        return {"n": 0, "mean": float("nan"), "median": float("nan"), "stdev": float("nan"), "p95": float("nan")}
    return {
        "n": n,
        "mean": statistics.mean(values),
        "median": statistics.median(values),
        "stdev": statistics.stdev(values) if n >= 2 else 0.0,
        "p95": statistics.quantiles(values, n=20)[18] if n >= 2 else values[0],
    }


def _fmt_bool(value: bool) -> str:
    return "true" if value else "false"


def write_deploy_overlay(
    path: Path,
    sessions: int,
    shared: bool,
    graphs: bool,
    mem0: float | None,
    mem1: float | None,
    profiler_cuda: bool = False,
) -> None:
    """Render the cell overlay next to personaplex.yaml (relative base_config).

    ``profiler_cuda`` adds the per-stage ``profiler: cuda`` config so the
    serving API's /start_profile and /stop_profile bracket a
    cudaProfilerApi capture range (see docs/contributing/profiling.md §6).
    """
    stage_extra = ["    profiler_config:", "      profiler: cuda"] if profiler_cuda else []
    lines = [
        "# Auto-generated by bench_personaplex_shared_mimi_matrix.py -- do not edit.",
        "base_config: personaplex.yaml",
        "",
        "duplex_session:",
        f"  max_sessions: {sessions}",
        "",
        "stages:",
        "  - stage_id: 0",
        f"    max_num_seqs: {sessions}",
    ]
    if mem0 is not None:
        lines.append(f"    gpu_memory_utilization: {mem0}")
    lines += [
        "    hf_overrides:",
        f"      mimi_cuda_graphs: {_fmt_bool(graphs)}",
        *stage_extra,
        "  - stage_id: 1",
        f"    max_num_seqs: {sessions}",
    ]
    if mem1 is not None:
        lines.append(f"    gpu_memory_utilization: {mem1}")
    lines += [
        "    hf_overrides:",
        f"      mimi_cuda_graphs: {_fmt_bool(graphs)}",
        f"      mimi_shared_decoder: {_fmt_bool(shared)}",
        *stage_extra,
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def wait_ready(url: str, proc: subprocess.Popen, log: Path, timeout: float) -> float:
    """Block until /health answers; return seconds since server launch."""
    start = time.monotonic()
    deadline = start + timeout
    while time.monotonic() < deadline:
        if proc.poll() is not None:
            tail = log.read_text(errors="replace").splitlines()[-40:] if log.exists() else []
            raise RuntimeError("server exited during startup:\n  " + "\n  ".join(tail))
        try:
            if httpx.get(f"{url}/health", timeout=2.0).status_code == 200:
                return time.monotonic() - start
        except Exception:
            pass
        time.sleep(2.0)
    raise TimeoutError(f"server not ready within {timeout}s (log: {log})")


def wait_port_free(port: int, timeout: float = 180.0) -> bool:
    """Block until nothing accepts on the port.

    Stage-engine children can outlive the launcher process group by minutes
    after SIGTERM; the next server launch must not race them for the bind.
    """
    import socket

    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        with socket.socket() as sock:
            sock.settimeout(0.5)
            if sock.connect_ex(("127.0.0.1", port)) != 0:
                return True
        time.sleep(2.0)
    return False


def probe_gpu_memory_mib(pgid: int) -> float | None:
    """Sum GPU memory of the server's process group after weight load, before load."""
    try:
        ps_out = subprocess.run(
            ["ps", "-eo", "pid,pgid", "--no-headers"], capture_output=True, text=True, timeout=10
        ).stdout
        group = {
            int(parts[0])
            for parts in (line.split() for line in ps_out.splitlines())
            if len(parts) >= 2 and int(parts[1]) == pgid
        }
        smi = subprocess.run(
            ["nvidia-smi", "--query-compute-apps=pid,used_gpu_memory", "--format=csv,noheader,nounits"],
            capture_output=True,
            text=True,
            timeout=10,
        ).stdout
    except Exception:
        return None
    rows: list[tuple[int, float]] = []
    for line in smi.splitlines():
        parts = [p.strip() for p in line.split(",")]
        if len(parts) != 2 or "[N/A]" in parts[1]:
            continue
        try:
            rows.append((int(parts[0]), float(parts[1])))
        except ValueError:
            continue
    total = sum(mib for pid, mib in rows if pid in group)
    if not total and rows:
        # In a container, nvidia-smi lists host-side pids that never match the
        # container's ps output; on this single-GPU box the server is the only
        # tenant, so attribute every compute app to it.
        total = sum(mib for _, mib in rows)
    if not total:
        try:
            used = subprocess.run(
                ["nvidia-smi", "--query-gpu=memory.used", "--format=csv,noheader,nounits"],
                capture_output=True,
                text=True,
                timeout=10,
            ).stdout
            total = float(used.strip().splitlines()[0])
        except Exception:
            return None
    return total or None


def run_driver(
    args: argparse.Namespace,
    url: str,
    sessions: int,
    load_frames: int,
    out_dir: Path,
    extra_args: list[str] | None = None,
) -> dict:
    """One driver invocation; parse its load-result.json (never overwritten)."""
    cmd = [
        sys.executable,
        str(DRIVER),
        "--url",
        url,
        "--model",
        args.model,
        "--input-wav",
        str(args.input_wav),
        "--sessions",
        str(sessions),
        "--load-frames",
        str(load_frames),
        "--output-dir",
        str(out_dir),
        "--timeout-s",
        str(args.driver_timeout_s),
    ]
    if args.max_client_rtf is not None:
        cmd += ["--max-client-rtf", str(args.max_client_rtf)]
    if args.expected_input_sha256:
        cmd += ["--expected-input-sha256", args.expected_input_sha256]
    if extra_args:
        cmd += extra_args
    print(f"    driver: {sessions} session(s), {load_frames} frames -> {out_dir.name}", flush=True)
    completed = subprocess.run(cmd, capture_output=True, text=True, timeout=args.driver_timeout_s + 300)
    result_path = out_dir / "load-result.json"
    if not result_path.is_file():
        raise RuntimeError(
            f"driver produced no load-result.json (rc={completed.returncode}):\n"
            + completed.stdout[-2000:]
            + completed.stderr[-2000:]
        )
    result = json.loads(result_path.read_text(encoding="utf-8"))
    result["driver_returncode"] = completed.returncode
    return result


def last_hit_rate(log: Path) -> str | None:
    """The server's periodic Mimi decode-graph hit-rate line, if it fired."""
    if not log.exists():
        return None
    hits = [line.strip() for line in log.read_text(errors="replace").splitlines() if "hit_rate=" in line]
    return hits[-1].split(" - ", 1)[-1] if hits else None


def run_cell(args: argparse.Namespace, cell: str, sessions: int, stamp_dir: Path) -> dict:
    shared, graphs = CELLS[cell]
    tag = f"{cell.lower()}_n{sessions}"
    cell_dir = stamp_dir / tag
    cell_dir.mkdir(parents=True, exist_ok=True)
    log = cell_dir / "server.log"
    deploy = REPO / "vllm_omni/deploy" / f"_autogen_pplex_matrix_{tag}.yaml"
    write_deploy_overlay(deploy, sessions, shared, graphs, args.gpu_mem_util_0, args.gpu_mem_util_1)

    cmd = [
        sys.executable,
        "-m",
        "vllm_omni.entrypoints.cli.main",
        "serve",
        args.model,
        "--omni",
        "--deploy-config",
        str(deploy),
        "--host",
        "127.0.0.1",
        "--port",
        str(args.port),
    ]
    env = dict(os.environ)
    env["PYTHONPATH"] = os.pathsep.join(p for p in (str(REPO), env.get("PYTHONPATH")) if p)
    if args.cuda_visible_devices:
        env["CUDA_VISIBLE_DEVICES"] = args.cuda_visible_devices

    print(f"\n=== cell {cell} (shared={shared} graphs={graphs}) sessions={sessions} ===", flush=True)
    print(f"  launching server (log: {log})", flush=True)
    with open(log, "w") as lf:
        proc = subprocess.Popen(cmd, env=env, stdout=lf, stderr=subprocess.STDOUT, start_new_session=True)
    url = f"http://127.0.0.1:{args.port}"
    try:
        load_time_s = wait_ready(url, proc, log, args.server_timeout_s)
        time.sleep(3.0)  # settle post-load allocations before the memory probe
        gpu_mib = probe_gpu_memory_mib(proc.pid)
        print(f"  server ready in {load_time_s:.1f}s, gpu={gpu_mib if gpu_mib is not None else 'n/a'} MiB", flush=True)

        if args.warmup:
            warmup_dir = cell_dir / "warmup"
            warmup_dir.mkdir(parents=True, exist_ok=True)
            try:
                run_driver(
                    args, f"ws://127.0.0.1:{args.port}/v1/realtime?duplex=1", 1, min(args.load_frames, 50), warmup_dir
                )
            except Exception as exc:
                print(f"  warning: warmup run failed: {exc}", flush=True)

        runs = []
        for i in range(1, args.runs + 1):
            runs.append(
                run_driver(
                    args,
                    f"ws://127.0.0.1:{args.port}/v1/realtime?duplex=1",
                    sessions,
                    args.load_frames,
                    cell_dir / f"run{i:02d}",
                )
            )

        rows = [row for run in runs for row in run["sessions"]]
        ok_rows = [row for row in rows if row.get("ok") is True]
        rtfs = [row["client_stream_rtf"] for row in ok_rows if isinstance(row.get("client_stream_rtf"), float)]
        audio_rtf_rows = [row["audio_rtf"] for row in ok_rows if isinstance(row.get("audio_rtf"), float)]
        ttfps = [
            row["client_first_audio_after_stream_start_ms"]
            for row in ok_rows
            if isinstance(row.get("client_first_audio_after_stream_start_ms"), float)
        ]
        p99s = [
            row["client_audio_packet_interval_ms"]["p99"]
            for row in ok_rows
            if isinstance(row.get("client_audio_packet_interval_ms"), dict)
            and isinstance(row["client_audio_packet_interval_ms"].get("p99"), float)
        ]
        summary = {
            "cell": cell,
            "mimi_shared_decoder": shared,
            "mimi_cuda_graphs": graphs,
            "sessions": sessions,
            "requested": sum(run["requested_sessions"] for run in runs),
            "passed": sum(run["passed_sessions"] for run in runs),
            "client_stream_rtf": _stats(rtfs),
            "audio_rtf": _stats(audio_rtf_rows),
            "client_first_audio_ms": _stats(ttfps),
            "client_packet_interval_p99_ms": _stats(p99s),
            "audio_underrun_events": sum(row.get("audio_underrun_event_count") or 0 for row in ok_rows),
            "server_load_time_s": load_time_s,
            "server_gpu_memory_mib_after_load": gpu_mib,
            "mimi_graph_hit_rate_log": last_hit_rate(log),
            "driver_returncodes": [run["driver_returncode"] for run in runs],
        }
        print(json.dumps(summary, indent=2, ensure_ascii=False), flush=True)
        return summary
    finally:
        print("  shutting down server", flush=True)
        try:
            os.killpg(os.getpgid(proc.pid), signal.SIGTERM)
        except Exception:
            proc.terminate()
        try:
            proc.wait(timeout=60)
        except subprocess.TimeoutExpired:
            try:
                os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
            except Exception:
                proc.kill()
            proc.wait(timeout=20)
        wait_port_free(args.port)
        deploy.unlink(missing_ok=True)


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--model", default=DEFAULT_MODEL)
    p.add_argument("--input-wav", required=True, help="Speech clip tiled by the driver as paced session input.")
    p.add_argument("--sessions", type=int, nargs="+", default=[1, 2, 4, 8, 16])
    p.add_argument("--cells", choices=sorted(CELLS), nargs="+", default=["A", "B", "C", "D"])
    p.add_argument(
        "--runs", type=int, default=3, help="Recorded driver runs per (cell, sessions); 1 warmup precedes them."
    )
    p.add_argument("--warmup", type=int, default=1)
    p.add_argument("--load-frames", type=int, default=375, help="Input frames per session (375 = 30 s at 12.5 Hz).")
    p.add_argument("--max-client-rtf", type=float, help="Pass through to the driver as the session acceptance ceiling.")
    p.add_argument(
        "--expected-input-sha256", help="Fail before opening sessions unless the input WAV matches this SHA-256."
    )
    p.add_argument("--port", type=int, default=8099)
    p.add_argument("--server-timeout-s", type=float, default=1800.0)
    p.add_argument("--driver-timeout-s", type=float, default=900.0)
    p.add_argument(
        "--gpu-mem-util-0",
        type=float,
        default=None,
        help="Stage 0 gpu_memory_utilization override; default keeps personaplex.yaml (0.4). "
        "Raise for high N: each live session holds ~1.5 GiB of Stage 0 KV.",
    )
    p.add_argument("--gpu-mem-util-1", type=float, default=None, help="Stage 1 override; default keeps 0.3.")
    p.add_argument("--cuda-visible-devices", default="0")
    p.add_argument("--output-dir", default="./pplex_shared_mimi_results")
    return p.parse_args()


def main() -> None:
    args = parse_args()
    args.input_wav = Path(args.input_wav).resolve()
    input_sha = hashlib.sha256(args.input_wav.read_bytes()).hexdigest()
    out = Path(args.output_dir).resolve()
    stamp_dir = out / time.strftime("%Y%m%d-%H%M%S")
    stamp_dir.mkdir(parents=True, exist_ok=True)
    print(f"results: {stamp_dir}")
    print(f"input: {args.input_wav} sha256={input_sha}")

    summaries = []
    failed = False
    for cell in args.cells:
        for sessions in args.sessions:
            try:
                summaries.append(run_cell(args, cell, sessions, stamp_dir))
            except Exception as exc:
                print(f"  cell {cell} n={sessions} FAILED: {exc}", flush=True)
                failed = True

    matrix_path = stamp_dir / "matrix.json"
    matrix_path.write_text(
        json.dumps(
            {
                "model": args.model,
                "input_wav": str(args.input_wav),
                "input_sha256": input_sha,
                "load_frames": args.load_frames,
                "runs_per_cell": args.runs,
                "cells": summaries,
            },
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )
    print(f"\nMatrix written to {matrix_path}")

    print("\n=== SUMMARY (pass-rate counts sessions across all recorded runs) ===")
    header = (
        f"{'cell':>4} {'N':>3} {'pass':>9} {'rtf med':>8} {'a_rtf med':>9} "
        f"{'ttfp med':>9} {'underrun':>8} {'p99 ms':>7} {'load s':>7} {'gpu MiB':>8}"
    )
    print(header)
    print("-" * len(header))
    for s in summaries:
        rtf, artf, ttfp = s["client_stream_rtf"], s["audio_rtf"], s["client_first_audio_ms"]
        print(
            f"{s['cell']:>4} {s['sessions']:>3} {s['passed']:>4}/{s['requested']:<4} "
            f"{rtf['median']:>8.3f} {artf['median']:>9.3f} {ttfp['median']:>9.0f} "
            f"{s['audio_underrun_events']:>8} {s['client_packet_interval_p99_ms']['median']:>7.0f} "
            f"{s['server_load_time_s']:>7.1f} {s['server_gpu_memory_mib_after_load'] or float('nan'):>8.0f}"
        )

    if failed:
        sys.exit(1)


if __name__ == "__main__":
    main()
